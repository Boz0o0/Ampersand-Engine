/**
 * @brief Writes the JSON files of each test in its own temporary directory,
 * and gives a SceneManager knowing the test types (no backend is used, so no
 * window or audio device is opened).
 */
class SceneManagerTest : public ::testing::Test {
protected:
    void SetUp() override {
        _root =
            std::filesystem::temp_directory_path() /
            ("ampersand_scene_" + std::string(::testing::UnitTest::GetInstance()
                                                  ->current_test_info()
                                                  ->name()));
        std::filesystem::remove_all(_root);
        std::filesystem::create_directories(_root);
        _scenes.registerResource<Score>("Score");
        _scenes.registerResource<Level>("Level");
        _scenes.registerResource<Settings>("Settings", ResourceScope::Config);
        _scenes.registerComponent<Stats>("Stats");
    }

    void TearDown() override { std::filesystem::remove_all(_root); }

    /** @brief Writes a file under the root, with "version" added. */
    void write(const std::string& name, const std::string& text) const {
        json data = json::parse(text);
        data["version"] = SceneManager::kVersion;
        std::ofstream(_root / name) << data.dump();
    }

    /**
     * @brief Writes a configuration with scenes "a" and "b" (a.json and
     * b.json), the given resources and start scene (none if empty), and
     * returns its path.
     */
    [[nodiscard]] std::string config(
        const std::string& name, const std::string& resources = "null",
        const std::string& startScene = "a") const {
        json data =
            json::parse(R"({"scenes": {"a": "a.json", "b": "b.json"}})");
        data["version"] = SceneManager::kVersion;
        data["gameRoot"] = _root.string();
        data["resources"] = json::parse(resources);
        if (!startScene.empty()) {
            data["startScene"] = startScene;
        }
        std::ofstream(_root / name) << data.dump();
        return (_root / name).string();
    }

    /** @brief Returns the number of entities with a Stats component. */
    std::size_t statsCount() { return _world.owners<Stats>().size(); }

    std::filesystem::path _root;
    World _world;
    SceneManager _scenes;
};

TEST_F(SceneManagerTest, LoadsTheConfigurationAndItsStartScene) {
    write("a.json", R"({"entities": [
        {"components": {"Stats": {"health": 5, "speed": 1}}}
    ]})");

    _scenes.loadConfig(_world,
                       config("config.json", R"({"Score": {"value": 3}})"));

    EXPECT_EQ(_scenes.getCurrentScene(), "a");
    EXPECT_EQ(_world.getResource<Score>().value, 3);
    ASSERT_EQ(statsCount(), 1U);
    EXPECT_EQ(_world.get<Stats>(_world.owners<Stats>().front()).health, 5);
}

TEST_F(SceneManagerTest, LoadSceneReplacesTheEntitiesAndResources) {
    write("a.json", R"({"resources": {"Level": {"index": 1}}, "entities": [
        {"components": {"Stats": {"health": 1, "speed": 1}}}
    ]})");
    write("b.json", R"({"resources": {"Level": {"index": 2}}, "entities": [
        {"components": {"Stats": {"health": 2, "speed": 1}}},
        {"components": {"Stats": {"health": 2, "speed": 1}}}
    ]})");
    _scenes.loadConfig(_world, config("config.json"));

    _scenes.loadScene(_world, "b");

    EXPECT_EQ(_scenes.getCurrentScene(), "b");
    EXPECT_EQ(_world.getResource<Level>().index, 2);
    EXPECT_EQ(statsCount(), 2U);
}

