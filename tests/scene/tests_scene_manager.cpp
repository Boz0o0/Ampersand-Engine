TEST_F(SceneManagerTest, ScriptsOfASceneRunAndAreDestroyedWithIt) {
    std::ofstream(_root / "leave.lua") << R"(
        local S = {}
        function S:start() mark("started") end
        function S:onDestroy() mark("left") end
        return S
    )";
    write("a.json", R"({"entities": [
        {"components": {"Scripts": {"scripts": ["leave.lua"]}}}
    ]})");
    write("b.json", R"({})");
    _world.addResource<Clock>(Clock{.dt = 0.5F});
    ScriptingSystem system;
    std::vector<std::string> marks;
    system.lua().set_function(
        "mark", [&marks](const std::string& mark) { marks.push_back(mark); });
    _scenes.loadConfig(_world, config("config.json"));

    system.update(_world);
    EXPECT_EQ(marks, std::vector<std::string>{"started"});

    _scenes.loadScene(_world, "b");
    system.update(_world);
    EXPECT_EQ(marks, (std::vector<std::string>{"started", "left"}));
}

