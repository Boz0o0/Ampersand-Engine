TEST_F(SceneManagerTest, EngineBackendsAndInputAreConfigOnly) {
    std::vector<std::string> names;
#ifdef AMPERSAND_MODULE_RENDER
    names.emplace_back("Renderer");
#endif
#ifdef AMPERSAND_MODULE_AUDIO
    names.emplace_back("AudioListener");
#endif
#ifdef AMPERSAND_MODULE_INPUT
    names.emplace_back("InputManager");
#endif
    write("a.json", R"({})");
    _scenes.loadConfig(_world, config("config.json"));

    for (const auto& name : names) {
        json scene = {{"version", SceneManager::kVersion}};
        scene["resources"][name] = json::object();
        std::ofstream(_root / "b.json") << scene.dump();

        try {
            _scenes.loadScene(_world, "b");
            ADD_FAILURE() << name << " was loaded from a scene";
        } catch (const std::runtime_error& error) {
            EXPECT_NE(std::string(error.what()).find("only allowed"),
                      std::string::npos)
                << error.what();
        }
        EXPECT_EQ(_scenes.getCurrentScene(), "a");
    }
}

