TEST_F(SceneManagerTest, PrefabFieldsAreMergedWithTheScene) {
    write("prefab.json", R"({
        "components": {"Stats": {"health": 1, "speed": 2}},
        "children": [{"components": {"Stats": {"health": 7, "speed": 1}}}]
    })");
    write("a.json", R"({"entities": [
        {"prefab": "prefab.json", "components": {"Stats": {"speed": 9}}}
    ]})");

    _scenes.loadConfig(_world, config("config.json"));

    const auto& owners = _world.owners<Stats>();
    ASSERT_EQ(owners.size(), 2U);
    const bool firstIsRoot = _world.parent(owners[0]) == Entity{};
    const Entity root = firstIsRoot ? owners[0] : owners[1];
    const Entity child = firstIsRoot ? owners[1] : owners[0];
    EXPECT_EQ(_world.parent(child), root);
    EXPECT_EQ(_world.get<Stats>(root).health, 1);
    EXPECT_EQ(_world.get<Stats>(root).speed, 9);
    EXPECT_EQ(_world.get<Stats>(child).health, 7);
}

